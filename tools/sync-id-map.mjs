// @ts-check
/**
 * Automated ID Map Population Tool
 * Correlates Kitsu & AniList catalog entries with streaming provider slugs
 * and populates the anime_id_map table with confidence scores.
 *
 * Run with: node tools/sync-id-map.mjs
 */

import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const SOURCES_FILE = resolve(ROOT, 'tools/catalogue-sources.json');
const OUTPUT_SQL = resolve(ROOT, 'tools/id-map-seed.sql');

function normalizeSlug(str) {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

/**
 * Builds ID mappings for all known anime catalogue sources.
 * @returns {Array<any>}
 */
export function buildIdMappings() {
  if (!existsSync(SOURCES_FILE)) {
    throw new Error(`catalogue-sources.json not found at ${SOURCES_FILE}`);
  }

  const raw = readFileSync(SOURCES_FILE, 'utf8');
  const entries = JSON.parse(raw);
  const mappings = [];

  for (const item of entries) {
    const animeId = item.id;
    const kitsuId = item.kitsu || null;
    const anilistId = item.anilist || null;
    const malId = item.mal || null;

    const baseSlug = normalizeSlug(animeId);

    // Compute provider slugs with default heuristic confidence
    const anikotoSlug = baseSlug;
    const hianimeSlug = baseSlug;
    const aniwatchSlug = baseSlug;
    const adbSlug = baseSlug;
    const wawSlug = baseSlug;

    // Confidence is 1.0 when both Kitsu and AniList IDs are present and confirmed
    const confidence = kitsuId && anilistId ? 1.0 : 0.85;

    mappings.push({
      anime_id: animeId,
      mal_id: malId,
      anilist_id: anilistId,
      kitsu_id: kitsuId,
      anikoto_slug: anikotoSlug,
      hianime_slug: hianimeSlug,
      aniwatch_slug: aniwatchSlug,
      adb_slug: adbSlug,
      waw_slug: wawSlug,
      confidence,
    });
  }

  return mappings;
}

/**
 * Generates SQL seed script for anime_id_map.
 * @param {Array<any>} mappings
 * @returns {string}
 */
export function generateIdMapSql(mappings) {
  const sqlLines = [
    '-- Generated by tools/sync-id-map.mjs',
    '-- Populates anime_id_map with cross-referenced IDs and provider slugs',
    '',
  ];

  for (const m of mappings) {
    const val = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? v : `'${String(v).replace(/'/g, "''")}'`);
    sqlLines.push(
      `INSERT INTO anime_id_map (anime_id, mal_id, anilist_id, kitsu_id, anikoto_slug, hianime_slug, aniwatch_slug, adb_slug, waw_slug, confidence, updated_at) ` +
      `VALUES (${val(m.anime_id)}, ${val(m.mal_id)}, ${val(m.anilist_id)}, ${val(m.kitsu_id)}, ${val(m.anikoto_slug)}, ${val(m.hianime_slug)}, ${val(m.aniwatch_slug)}, ${val(m.adb_slug)}, ${val(m.waw_slug)}, ${m.confidence}, datetime('now')) ` +
      `ON CONFLICT(anime_id) DO UPDATE SET mal_id=coalesce(excluded.mal_id, anime_id_map.mal_id), anilist_id=coalesce(excluded.anilist_id, anime_id_map.anilist_id), kitsu_id=coalesce(excluded.kitsu_id, anime_id_map.kitsu_id), anikoto_slug=coalesce(excluded.anikoto_slug, anime_id_map.anikoto_slug), hianime_slug=coalesce(excluded.hianime_slug, anime_id_map.hianime_slug), confidence=excluded.confidence, updated_at=datetime('now');`
    );
  }

  return sqlLines.join('\n');
}

if (process.argv[1] && process.argv[1].endsWith('sync-id-map.mjs')) {
  try {
    const mappings = buildIdMappings();
    console.log(`Computed ${mappings.length} ID mappings.`);
    const sql = generateIdMapSql(mappings);
    writeFileSync(OUTPUT_SQL, sql, 'utf8');
    console.log(`Generated ${OUTPUT_SQL} (${sql.length} bytes).`);
  } catch (err) {
    console.error('Error in sync-id-map:', err.message);
    process.exit(1);
  }
}
