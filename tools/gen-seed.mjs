/* Emits seed.sql from the invented rows in src/data/anime.ts.
   Run: node tools/gen-seed.mjs --force-prototype  ->  seed.sql

   Superseded by tools/sync-catalogue.mjs, which builds seed.sql from the real Kitsu and
   AniList catalogue. Running this generator against the live database would replace every
   real title, episode and air time with prototype fiction, so it now refuses to run
   without --force-prototype. */

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ANIME, GENRES, toSeconds } from '../src/data/anime.ts';

if (!process.argv.includes('--force-prototype')) {
  console.error(
    'Refusing to run: this writes prototype rows over seed.sql.\n' +
      '  For the real catalogue: node tools/sync-catalogue.mjs\n' +
      '  To rebuild the prototype seed deliberately: node tools/gen-seed.mjs --force-prototype',
  );
  process.exit(1);
}

/* The module hands out resolved URLs; the DB stores keys so the client keeps
   choosing the URL scheme (public dir vs Media Library) at render time. */
const artKey = (url) => {
  const m = /\/art\/(.+)\.jpe?g$/i.exec(url);
  if (!m) throw new Error(`not an art url: ${url}`);
  return m[1];
};

const text = (v) => (v === undefined || v === null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === undefined || v === null || Number.isNaN(v) ? 'NULL' : String(v));
const json = (v) => text(JSON.stringify(v));
const sep = (rows) => rows.map((r) => r + ';').join('\n');

const out = ['-- Generated by tools/gen-seed.mjs — do not edit by hand.', ''];

out.push(
  sep(
    GENRES.map((g, i) =>
      `INSERT OR REPLACE INTO genre (id,label,tagline,art,accent,position) VALUES (${text(g.id)},${text(g.label)},${text(
        g.tagline,
      )},${text(artKey(g.art))},${text(g.accent)},${i})`,
    ),
  ),
  '',
);

out.push(
  sep(
    ANIME.map((a) => {
      const s = a.schedule;
      return `INSERT OR REPLACE INTO anime (id,title,native,year,rating,season,kind,status,art,key_art,accent,synopsis,rank,alt_seasons,sched_day,sched_day_label,sched_date,sched_time,sched_season) VALUES (${text(
        a.id,
      )},${text(a.title)},${text(a.native)},${num(a.year)},${num(a.rating)},${text(a.season)},${text(a.kind)},${text(
        a.status,
      )},${text(artKey(a.poster))},${text(artKey(a.key))},${text(a.accent)},${text(
        a.synopsis,
      )},${num(a.rank)},${json(a.altSeasons)},${num(s?.day)},${text(s?.dayLabel)},${text(s?.date)},${text(
        s?.time,
      )},${text(s?.season)})`;
    }),
  ),
  '',
);

out.push(
  sep(
    ANIME.flatMap((a) =>
      a.genres.map((g) => `INSERT OR REPLACE INTO anime_genre (anime_id,genre_id) VALUES (${text(a.id)},${text(g)})`),
    ),
  ),
  '',
);

out.push(
  sep(
    ANIME.flatMap((a) =>
      a.episodes.map((e) => {
        const seconds = toSeconds(e.runtime);
        return `INSERT OR REPLACE INTO episode (id,anime_id,n,title,runtime,runtime_seconds,thumb,synopsis,markers) VALUES (${text(
          `${a.id}#${e.n}`,
        )},${text(a.id)},${e.n},${text(e.title)},${text(e.runtime)},${num(seconds)},${text(
          artKey(e.thumb),
        )},${text(e.synopsis)},${json(e.markers)})`;
      }),
    ),
  ),
  '',
);

const target = resolve(import.meta.dirname, '..', 'seed.sql');
writeFileSync(target, out.join('\n'), 'utf8');
console.log(
  `seed.sql: ${GENRES.length} genres, ${ANIME.length} anime, ${ANIME.reduce(
    (n, a) => n + a.episodes.length,
    0,
  )} episodes, ${ANIME.reduce((n, a) => n + a.genres.length, 0)} links`,
);
